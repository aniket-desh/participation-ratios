"""Tables the definition asks to report, from results.json -> tables.md.

1. Prediction quality per main run: tail-mean final-position KL(Bayes||model) (steps 15k-20k) and the last
   evaluation, against the short-window floors kl_lastk_final[k], k = 1..4 (KL of the best predictor that sees
   only the last k tokens; passing the bar means beating the k = 4 floor).
2. Per site, cell mean +- sample SD over the 3 seeds (all runs, passing or not; the pass column says how many pass)
   at step 0 and step 20,000: PR(C_h), the belief-specific R2 gain R2(m_token) - R2(last_token), and the gated
   factor-1 shares (m, u) of the token-partialled belief metric (nan = gated out in that seed).
3. Per run and site at step 20,000: PR(C_h) and the R2 gain.
"""
import json
import sys
from pathlib import Path

import numpy as np

recs = json.loads(Path(sys.argv[1]).read_text())
main = [r for r in recs if "_q" in r["run"] and r["analysis"] == "analysis"]
STEP = max(r["step"] for r in main)
ARCH, Q2 = ["base", "nomlp", "preln"], [0.25, 0.8]
SITES = ["resid_pre", "ln1", "attn_out", "resid_mid", "ln2", "mlp_out", "resid_post"]
gain = lambda s: s["m_token"]["r2_heldout"] - s["last_token"]["r2_heldout"]
f1 = lambda s, cs: s[cs]["partialled"]["factor1_share"] if gain(s) >= 0.01 else np.nan
Q = {"PR(C_h)": lambda s: s["C_h"]["pr"], "R2 gain": gain, "f1 share (m)": lambda s: f1(s, "m_token"),
     "f1 share (u)": lambda s: f1(s, "u_token")}
get = lambda a, q, step: sorted([r for r in main if r["arch"] == a and r["q2"] == q and r["step"] == step],
                                key=lambda r: r["seed"])
passes = lambda r: r["kl_final_tailmean"] < r["kl_lastk_final"]["4"]


def ms(x):
    x = np.array(x, float); n = np.isfinite(x).sum()
    if n == 0:
        return "—"
    m = np.nanmean(x)
    return f"{m:.3f} ± {np.nanstd(x, ddof=1):.3f}" + ("" if n == len(x) else f" (n={n})") if n > 1 else f"{m:.3f} (n=1)"


L = [f"# Tables: transformer-ablations\n\nGenerated by `tables.py` from `results.json`. Step {STEP} unless stated. "
     "Seeds 0, 1, 2 per cell; ± is the sample SD over seeds.\n",
     "## 1. Prediction quality per main run (final position, nats)\n",
     "| arch | q2 | seed | tail-mean KL | last-eval KL | floor k=1 | k=2 | k=3 | k=4 | passes bar |",
     "|---|---|---|---|---|---|---|---|---|---|"]
for a in ARCH:
    for q in Q2:
        for r in get(a, q, STEP):
            fl = r["kl_lastk_final"]
            L.append(f"| {a} | {q} | {r['seed']} | {r['kl_final_tailmean']:.5f} | {r['kl_final']:.5f} | "
                     + " | ".join(f"{fl[k]:.5f}" for k in "1234") + f" | {'yes' if passes(r) else 'no'} |")
for step in [0, STEP]:
    L += [f"\n## 2. Per-site cell means, step {step}\n"]
    for q in Q2:
        L += [f"\n### q2 = {q}\n", "| arch | site | pass | " + " | ".join(Q) + " |", "|---|---|---|" + "---|" * len(Q)]
        for a in ARCH:
            rs = get(a, q, step); npass = sum(passes(r) for r in get(a, q, STEP))
            for site in SITES:
                key = f"L0.{site}"
                if key not in rs[0]["sites"]:
                    continue
                L.append(f"| {a} | {site} | {npass}/3 | " + " | ".join(ms([fn(r["sites"][key]) for r in rs]) for fn in Q.values()) + " |")
L += [f"\n## 3. Per run and site, step {STEP}: PR(C_h) / R2 gain\n",
      "| run | " + " | ".join(SITES) + " |", "|---|" + "---|" * len(SITES)]
for a in ARCH:
    for q in Q2:
        for r in get(a, q, STEP):
            L.append(f"| {a} q2={q} s{r['seed']} | " + " | ".join(
                f"{r['sites'][f'L0.{s}']['C_h']['pr']:.2f} / {gain(r['sites'][f'L0.{s}']):.3f}" if f"L0.{s}" in r["sites"] else "—"
                for s in SITES) + " |")
Path(sys.argv[2]).write_text("\n".join(L) + "\n")
print("->", sys.argv[2])
